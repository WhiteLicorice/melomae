"""Build the decode test fixtures. Dev-only; needs an ffmpeg with libopus.

The script reads the read-only Apollo asset at ``C:\\Lab\\Apollo\\asserts\\input_wav.wav``
(CC BY-SA 4.0) and writes each supported input format plus a matching ffmpeg reference decode
into ``crates/melomae-core/tests/fixtures``. It also synthesizes a logarithmic sweep and the
ffmpeg swr resample of it, which the resampler is scored against.

Nothing here is committed. ``crates/melomae-core/tests/fixtures`` is gitignored: the files are
large, and one of them is derived from the read-only source. The Rust tests read whatever the
script produced and skip a case with a message when a fixture is absent, so a machine without
ffmpeg still builds and tests.

    python tools/fixtures/make_fixtures.py

Set ``MELOMAE_FFMPEG`` to point at a specific ffmpeg, ``MELOMAE_SOURCE_WAV`` to override the
source, and ``MELOMAE_FIXTURES`` to write somewhere else.
"""

from __future__ import annotations

import math
import os
import shutil
import struct
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURES_DIR = Path(
    os.environ.get("MELOMAE_FIXTURES", REPO_ROOT / "crates" / "melomae-core" / "tests" / "fixtures")
)
SOURCE_WAV = Path(
    os.environ.get("MELOMAE_SOURCE_WAV", r"C:\Lab\Apollo\asserts\input_wav.wav")
)

# The ffmpeg the owner used is the one inside the conda environment. Prefer it, then an explicit
# override, then whatever is on PATH.
FFMPEG_CANDIDATES = [
    os.environ.get("MELOMAE_FFMPEG"),
    r"C:\Users\Ren\miniconda3\envs\look2hear_win\Library\bin\ffmpeg.exe",
    shutil.which("ffmpeg"),
]

# The swr settings the owner's old pipeline used (C:\Lab\Apollo\inference2.py:39).
SWR_FILTER = "aresample=resampler=swr:filter_size=256:phase_shift=24:cutoff=0.98"

# The named inputs with characters that broke the owner's old batch script.
AWKWARD_NAMES = ["Florida!!!.opus", "Habits (Stay High).opus", "Sigur Rós.flac"]


def find_ffmpeg() -> str:
    for candidate in FFMPEG_CANDIDATES:
        if candidate and Path(candidate).is_file():
            return candidate
    raise SystemExit("no ffmpeg found; set MELOMAE_FFMPEG to the conda ffmpeg")


def run(ffmpeg: str, arguments: list[str]) -> None:
    subprocess.run(
        [ffmpeg, "-hide_banner", "-loglevel", "error", "-y", *arguments],
        check=True,
    )


def encode(ffmpeg: str, source: Path, target: Path, arguments: list[str]) -> None:
    print(f"encode {target.name}")
    run(ffmpeg, ["-i", str(source), *arguments, str(target)])


def decode_reference(
    ffmpeg: str, source: Path, target: Path, rate: int, channels: int, decoder: str | None = None
) -> None:
    print(f"reference {target.name}")
    input_decoder = ["-c:a", decoder] if decoder else []
    run(
        ffmpeg,
        [
            *input_decoder,
            "-i",
            str(source),
            "-map",
            "0:a:0",
            "-ar",
            str(rate),
            "-ac",
            str(channels),
            "-f",
            "f32le",
            "-c:a",
            "pcm_f32le",
            str(target),
        ],
    )


def write_wav_f32(path: Path, sample_rate: int, channels: list[list[float]]) -> None:
    """Write planar float samples as a 32-bit float WAV."""
    channel_count = len(channels)
    frames = len(channels[0])
    data = bytearray()
    for frame in range(frames):
        for channel in channels:
            data += struct.pack("<f", channel[frame])
    block_align = channel_count * 4
    header = b"RIFF" + struct.pack("<I", 36 + len(data)) + b"WAVE"
    header += b"fmt " + struct.pack(
        "<IHHIIHH", 16, 3, channel_count, sample_rate, sample_rate * block_align, block_align, 32
    )
    header += b"data" + struct.pack("<I", len(data))
    path.write_bytes(header + bytes(data))


def write_sweep(path: Path, sample_rate: int, seconds: float, start: float, end: float) -> None:
    """Write a logarithmic frequency sweep, ``start`` to ``end`` Hz, as float stereo."""
    frames = int(sample_rate * seconds)
    rate_per_second = (end / start) ** (1.0 / seconds)
    log_rate = math.log(rate_per_second)
    samples = []
    for i in range(frames):
        t = i / sample_rate
        phase = 2.0 * math.pi * start * (rate_per_second**t - 1.0) / log_rate
        samples.append(0.5 * math.sin(phase))
    write_wav_f32(path, sample_rate, [samples, list(samples)])


def write_attribution() -> None:
    text = (
        "# Fixture attribution\n\n"
        "Generated by `tools/fixtures/make_fixtures.py`. Do not commit these files.\n\n"
        "The encoded inputs and the ffmpeg reference decodes are derived from\n"
        "`C:\\Lab\\Apollo\\asserts\\input_wav.wav`, which is part of the Apollo project\n"
        "(<https://github.com/JusperLee/Apollo>) and is licensed CC BY-SA 4.0.\n\n"
        "Apollo: Li, Kai and Luo, Yi, \"Apollo: Band-sequence Modeling for High-Quality Music\n"
        "Restoration in Compressed Audio\", ICASSP 2025.\n\n"
        "The sweep fixture is synthesized by the script and carries no third-party rights.\n"
    )
    (FIXTURES_DIR / "ATTRIBUTION.md").write_text(text, encoding="utf-8")


def main() -> int:
    ffmpeg = find_ffmpeg()
    if not SOURCE_WAV.is_file():
        raise SystemExit(f"source WAV not found: {SOURCE_WAV}")

    FIXTURES_DIR.mkdir(parents=True, exist_ok=True)

    # (name, encoder arguments, native rate, channels, decoder override)
    encoded = [
        ("wav_44100.wav", ["-c:a", "pcm_f32le"], 44100, 2, None),
        ("aiff_44100.aiff", ["-c:a", "pcm_s24be"], 44100, 2, None),
        ("flac_44100.flac", ["-c:a", "flac"], 44100, 2, None),
        ("mp3_44100.mp3", ["-c:a", "libmp3lame", "-b:a", "320k"], 44100, 2, None),
        ("aac_44100.m4a", ["-c:a", "aac", "-b:a", "256k"], 44100, 2, None),
        ("alac_44100.m4a", ["-c:a", "alac"], 44100, 2, None),
        ("vorbis_44100.ogg", ["-c:a", "libvorbis", "-q:a", "6"], 44100, 2, None),
        ("opus_48000.opus", ["-c:a", "libopus", "-b:a", "256k"], 48000, 2, "libopus"),
        ("opus_48000.webm", ["-c:a", "libopus", "-b:a", "256k"], 48000, 2, "libopus"),
    ]

    for name, arguments, rate, channels, decoder in encoded:
        target = FIXTURES_DIR / name
        encode(ffmpeg, SOURCE_WAV, target, arguments)
        decode_reference(ffmpeg, target, FIXTURES_DIR / f"{name}.ffmpeg.f32", rate, channels, decoder)

    # The named inputs re-use the Opus and FLAC encodes under the awkward names.
    shutil.copyfile(FIXTURES_DIR / "opus_48000.opus", FIXTURES_DIR / AWKWARD_NAMES[0])
    shutil.copyfile(FIXTURES_DIR / "opus_48000.opus", FIXTURES_DIR / AWKWARD_NAMES[1])
    shutil.copyfile(FIXTURES_DIR / "flac_44100.flac", FIXTURES_DIR / AWKWARD_NAMES[2])

    # The sweep and its ffmpeg swr resample, for the resampler SNR check.
    sweep = FIXTURES_DIR / "sweep_48000.wav"
    print(f"synthesize {sweep.name}")
    write_sweep(sweep, 48000, 3.0, 20.0, 20000.0)
    print("reference sweep_44100.swr.f32")
    run(
        ffmpeg,
        [
            "-i",
            str(sweep),
            "-af",
            SWR_FILTER,
            "-ar",
            "44100",
            "-ac",
            "2",
            "-f",
            "f32le",
            "-c:a",
            "pcm_f32le",
            str(FIXTURES_DIR / "sweep_44100.swr.f32"),
        ],
    )

    write_attribution()
    print(f"wrote fixtures to {FIXTURES_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
